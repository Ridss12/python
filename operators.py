# operators
'''1. Arithmetic operators: +, -, *, / etc.
2. Assignment operators: =, +=, -= etc.
3. Comparison operators: ==, >, >=, <, != etc.
4. Logical operators: and, or, not'''

#1. Arithmetic operators: +, -, *, / etc.

a = 28
b = 12
c = 4
d = 7
e = 6

c = a + b
print(c)

#2. Assignment operators: =, +=, -= etc.
a = 28-12 # assign 28-12 in a
print(a)

b = 12
b +=12 # increment the value of b by 12 and then assign it to b
print(b)

c = 4
c -=12 # decrement the value of c by 12 and then assign it to b
print(c)

d = 7
d *=12 # multiply the value of d by 12 and then assign it to b
print(d)

e = 6
e *=12 # divide the value of e by 12 and then assign it to b
print(e)

#3. Comparison operators: ==, >, >=, <, != etc.

a = 28>12
print(a)

b = 28<12
print(b)

c = 3>=4
print(c)

d = 6>=6
print(d)

e = 6<=6
print(e)

f = 5!=7
print(f)

g = 12 == 12
print(g)

#4. Logical operators: and, or, not'''

#or truth table

a = True or False
print(a)

b = True or True
print(b)

c = False or False
print(c)

d = False or True
print(d)

#and truth table

e = True and False
print(e)

f = False and False
print(f)

g = False and True
print(g)

h = True and True
print(h)

# not truth table
 
i = not True
print(i)

j = not False
print(j)

print(not(True))
print(not(False))

